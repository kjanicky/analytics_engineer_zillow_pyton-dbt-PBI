select
    {{ dbt_utils.generate_surrogate_key(['listing_id', 'extracted_at']) }} as listing_snapshot_sk,
    listing_id,
    zip_code,
    price_usd,
    price_per_sqft,
    zestimate_usd,
    round((price_usd - zestimate_usd) / nullif(zestimate_usd, 0), 4) as valuation_gap_pct,
    rent_zestimate_usd,
    round(price_usd / nullif(rent_zestimate_usd * 12, 0), 2) as price_to_rent_ratio,
    tax_assessed_value_usd,
    price_change_usd,
    case when price_change_usd < 0 then true else false end as is_price_cut,
    days_on_zillow,
    extract(year from extracted_at) - year_built as property_age_years,
    is_fsbo,
    is_fsba,
    is_bank_owned,
    has_open_house,
    is_featured,
    broker_name,
    price_changed_at,
    extracted_at as snapshot_at,
    cast(extracted_at as date) as snapshot_date,
    cast(listed_at as date) as listed_date
from {{ ref('stg_zillow__listings') }}